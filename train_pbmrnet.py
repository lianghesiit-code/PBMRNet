def create_grad_scaler(enabled: bool):
    # torch.cuda.amp is used for compatibility with older PyTorch releases.
    return torch.cuda.amp.GradScaler(enabled=enabled)


def train_one_epoch(
    model: nn.Module,
    loader: DataLoader,
    optimizer: torch.optim.Optimizer,
    scaler,
    device: torch.device,
    cfg: TrainConfig,
    epoch: int,
) -> Dict[str, float]:
    model.train()
    total_sum = 0.0
    main_sum = 0.0
    branch_sum = 0.0
    sample_count = 0
    amp_enabled = bool(cfg.amp and device.type == "cuda")

    progress = tqdm(loader, desc=f"Epoch {epoch:03d} train", leave=False)
    for batch in progress:
        x = batch["x"].to(device, non_blocking=True).float()
        mask = batch["mask"].to(device, non_blocking=True).float()
        y = batch["y"].to(device, non_blocking=True).float()

        optimizer.zero_grad(set_to_none=True)
        with torch.cuda.amp.autocast(enabled=amp_enabled):
            output = model(x, mask)
            total_loss, main_loss, branch_loss = compute_training_loss(
                output,
                y,
                mask,
                cfg.huber_beta,
                cfg.lambda_branch,
            )

        scaler.scale(total_loss).backward()
        scaler.unscale_(optimizer)
        if cfg.grad_clip > 0:
            torch.nn.utils.clip_grad_norm_(model.parameters(), cfg.grad_clip)
        scaler.step(optimizer)
        scaler.update()

        batch_size = x.shape[0]
        sample_count += batch_size
        total_sum += float(total_loss.detach().item()) * batch_size
        main_sum += float(main_loss.detach().item()) * batch_size
        branch_sum += float(branch_loss.detach().item()) * batch_size
        progress.set_postfix(loss=f"{total_sum / sample_count:.5f}")

    return {
        "train_total_loss": total_sum / max(sample_count, 1),
        "train_main_loss": main_sum / max(sample_count, 1),
        "train_branch_loss": branch_sum / max(sample_count, 1),
    }


@torch.no_grad()
def evaluate(
    model: nn.Module,
    loader: DataLoader,
    device: torch.device,
    cfg: TrainConfig,
    patterns: Sequence[PatternSpec],
    description: str,
    collect_examples: int = 0,
) -> Tuple[
    Dict[str, float], pd.DataFrame, pd.DataFrame, pd.DataFrame, List[Dict[str, object]]
]:
    model.eval()
    accumulator = MetricAccumulator(patterns)
    amp_enabled = bool(cfg.amp and device.type == "cuda")
    examples: List[Dict[str, object]] = []

    progress = tqdm(loader, desc=description, leave=False)
    for batch in progress:
        x = batch["x"].to(device, non_blocking=True).float()
        mask = batch["mask"].to(device, non_blocking=True).float()
        y = batch["y"].to(device, non_blocking=True).float()
        pattern_indices = batch["pattern_index"].to(device, non_blocking=True).long()

        with torch.cuda.amp.autocast(enabled=amp_enabled):
            output = model(x, mask)
            total_loss, _, _ = compute_training_loss(
                output,
                y,
                mask,
                cfg.huber_beta,
                cfg.lambda_branch,
            )

        prediction = output["prediction_norm"] * output["std"] + output["mean"]
        if cfg.nonnegative_clip:
            prediction = prediction.clamp_min(0.0)
        repaired = torch.where(mask > 0.5, x, prediction)

        accumulator.update(
            repaired,
            y,
            mask,
            pattern_indices,
            output["gate_weights"],
            float(total_loss.item()),
        )

        if collect_examples > 0 and len(examples) < collect_examples:
            remaining = collect_examples - len(examples)
            take = min(remaining, x.shape[0])
            x_cpu = x[:take].cpu().numpy()
            mask_cpu = mask[:take].cpu().numpy()
            y_cpu = y[:take].cpu().numpy()
            repaired_cpu = repaired[:take].cpu().numpy()
            pattern_cpu = pattern_indices[:take].cpu().numpy()
            for index in range(take):
                missing_indices = np.flatnonzero(mask_cpu[index] < 0.5)
                examples.append(
                    {
                        "sample_id": str(batch["sample_id"][index]),
                        "clean_id": str(batch["clean_id"][index]),
                        "meter_id": str(batch["meter_id"][index]),
                        "pattern_id": patterns[int(pattern_cpu[index])].pattern_id,
                        "missing_indices": json.dumps(missing_indices.tolist()),
                        "true_missing": json.dumps(
                            y_cpu[index, missing_indices].round(6).tolist()
                        ),
                        "pred_missing": json.dumps(
                            repaired_cpu[index, missing_indices].round(6).tolist()
                        ),
                    }
                )

    overall, by_pattern, by_type, gate = accumulator.finalize()
    return overall, by_pattern, by_type, gate, examples


def make_loader(
    dataset: Dataset,
    batch_size: int,
    shuffle: bool,
    num_workers: int,
    seed: int,
    device: torch.device,
) -> DataLoader:
    generator = torch.Generator()
    generator.manual_seed(seed)
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=(device.type == "cuda"),
        drop_last=False,
        worker_init_fn=seed_worker,
        generator=generator,
        persistent_workers=False,
    )


def save_json(path: Path, payload: Mapping[str, object]) -> None:
    with path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)


def save_evaluation(
    out_dir: Path,
    prefix: str,
    overall: Mapping[str, float],
    by_pattern: pd.DataFrame,
    by_type: pd.DataFrame,
    gate: pd.DataFrame,
    examples: Sequence[Mapping[str, object]],
) -> None:
    save_json(out_dir / f"{prefix}_metrics.json", dict(overall))
    by_pattern.to_csv(out_dir / f"{prefix}_metrics_by_pattern.csv", index=False)
    by_type.to_csv(out_dir / f"{prefix}_metrics_by_type.csv", index=False)
    gate.to_csv(out_dir / f"{prefix}_gate_statistics.csv", index=False)
    if examples:
        pd.DataFrame(examples).to_csv(
            out_dir / f"{prefix}_prediction_examples.csv", index=False
        )


def plot_history(history: pd.DataFrame, out_path: Path) -> None:
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        return
    figure = plt.figure(figsize=(8, 5))
    axis = figure.add_subplot(111)
    axis.plot(history["epoch"], history["val_MAE"], label="Val MAE")
    axis.plot(history["epoch"], history["val_RMSE"], label="Val RMSE")
    axis.set_xlabel("Epoch")
    axis.set_ylabel("Error")
    axis.grid(True, alpha=0.3)
    axis.legend()
    figure.tight_layout()
    figure.savefig(out_path, dpi=160)
    plt.close(figure)


def main() -> None:
    cfg = parse_args()
    if cfg.ablation == "no_auxiliary_loss":
        cfg.lambda_branch = 0.0
    seed_everything(cfg.seed)

    data_dir = Path(cfg.data_dir)
    out_dir = Path(cfg.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    train_path = data_dir / "train.csv"
    val_path = data_dir / "val.csv"
    test_path = data_dir / "test.csv"
    required_paths = (train_path, val_path) if cfg.skip_test else (train_path, val_path, test_path)
    for path in required_paths:
        if not path.exists():
            raise FileNotFoundError(path)

    patterns, mixed_random_ratio = load_patterns(data_dir)
    pattern_to_index, pattern_index_to_name = make_pattern_maps(patterns)
    # During hyperparameter search, --skip_test enforces a strict validation-only
    # protocol: test.csv is neither loaded nor audited.
    data_audit = audit_datasets(
        train_path, val_path, None if cfg.skip_test else test_path, patterns
    )
    save_json(
        out_dir / "run_config.json",
        {
            "training": asdict(cfg),
            "patterns": [asdict(p) for p in patterns],
            "mixed_random_ratio": mixed_random_ratio,
            "data_audit": data_audit,
        },
    )

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    amp_enabled = bool(cfg.amp and device.type == "cuda")
    if device.type == "cuda":
        torch.cuda.reset_peak_memory_stats(device)
    print("=" * 80)
    print("CER gap-aware three-branch imputer training")
    print("=" * 80)
    print(f"Device: {device}")
    if device.type == "cuda":
        print(f"GPU: {torch.cuda.get_device_name(0)}")
    print(f"AMP: {amp_enabled}")
    print(f"Data directory: {data_dir.resolve()}")
    print(f"Output directory: {out_dir.resolve()}")
    print(f"Online patterns: {', '.join(p.pattern_id for p in patterns)}")
    print("Training pattern coverage: ALL 9 patterns per clean window per epoch")

    print("\nLoading train.csv ...")
    train_dataset = OnlineMaskTrainDataset(
        train_path,
        patterns,
        mixed_random_ratio,
        cfg.seed,
    )
    print("Loading val.csv ...")
    val_dataset = FixedMaskDataset(val_path, pattern_to_index)
    test_protocol_dataset = None
    if not cfg.skip_test:
        print("Loading test.csv for fixed-mask protocol check ...")
        test_protocol_dataset = FixedMaskDataset(test_path, pattern_to_index)
    check_mask_protocols(train_dataset, val_dataset, test_protocol_dataset)
    del test_protocol_dataset
    gc.collect()
    if train_dataset.sequence_length != val_dataset.x.shape[1]:
        raise RuntimeError("Train and validation sequence lengths differ")
    sequence_length = train_dataset.sequence_length
    print(f"Train clean windows: {train_dataset.num_clean_windows:,}")
    print(f"Effective training samples/epoch: {len(train_dataset):,}")
    print(f"Validation fixed-mask samples: {len(val_dataset):,}")
    print(f"Sequence length: {sequence_length}")

    train_loader = make_loader(
        train_dataset,
        cfg.batch_size,
        True,
        cfg.num_workers,
        cfg.seed + 10,
        device,
    )
    val_loader = make_loader(
        val_dataset,
        cfg.batch_size,
        False,
        cfg.num_workers,
        cfg.seed + 20,
        device,
    )

    model = SimpleGapAwareThreeBranchImputer(
        sequence_length=sequence_length,
        local_dim=cfg.local_dim,
        periodic_dim=cfg.periodic_dim,
        global_dim=cfg.global_dim,
        local_blocks=cfg.local_blocks,
        periodic_heads=cfg.periodic_heads,
        gate_hidden_dim=cfg.gate_hidden_dim,
        gate_input=cfg.gate_input,
        dropout=cfg.dropout,
        ablation=cfg.ablation,
    ).to(device)
    parameter_count = sum(p.numel() for p in model.parameters() if p.requires_grad)
    if parameter_count > 500_000:
        raise RuntimeError(f"Parameter limit exceeded: {parameter_count} > 500000")
    run_model_sanity_check(model, device)
    breakdown = parameter_breakdown(model)
    save_json(
        out_dir / "run_config.json",
        {
            "model_name": MODEL_NAME,
            "training": asdict(cfg),
            "model": {
                "local_dim": model.local_dim,
                "periodic_dim": model.periodic_dim,
                "global_dim": model.global_dim,
                "local_blocks": model.local_blocks,
                "periodic_heads": model.periodic_heads,
                "gate_hidden_dim": model.gate_hidden_dim,
                "gate_input": model.gate_input,
                "ablation": model.ablation,
                "dropout": cfg.dropout,
                "parameter_count": parameter_count,
                "parameter_breakdown": breakdown,
            },
            "patterns": [asdict(p) for p in patterns],
            "mixed_random_ratio": mixed_random_ratio,
            "data_audit": data_audit,
            "selection_policy": "Validation MAE selects the checkpoint; test is evaluated only after loading that checkpoint.",
        },
    )
    print("Model sanity check: PASS")
    print(f"Model: {MODEL_NAME}; gate_input: {cfg.gate_input}; ablation: {cfg.ablation}")
    print(f"Trainable parameters: {parameter_count:,}")

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=cfg.learning_rate,
        weight_decay=cfg.weight_decay,
    )
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer,
        mode="min",
        factor=cfg.scheduler_factor,
        patience=cfg.scheduler_patience,
    )
    scaler = create_grad_scaler(amp_enabled)

    best_mae = float("inf")
    best_epoch = 0
    epochs_without_improvement = 0
    history_rows: List[Dict[str, float]] = []
    checkpoint_path = out_dir / "best_model.pt"
    start_time = time.time()

    for epoch in range(1, cfg.epochs + 1):
        train_dataset.set_epoch(epoch)
        epoch_start = time.time()
        train_result = train_one_epoch(
            model,
            train_loader,
            optimizer,
            scaler,
            device,
            cfg,
            epoch,
        )
        val_overall, _, _, _, _ = evaluate(
            model,
            val_loader,
            device,
            cfg,
            patterns,
            description=f"Epoch {epoch:03d} val",
        )
        scheduler.step(val_overall["MAE"])
        current_lr = float(optimizer.param_groups[0]["lr"])
        epoch_seconds = time.time() - epoch_start

        row = {
            "epoch": epoch,
            **train_result,
            "val_loss": val_overall["loss"],
            "val_MAE": val_overall["MAE"],
            "val_RMSE": val_overall["RMSE"],
            "val_SMAPE": val_overall["SMAPE"],
            "val_PCC": val_overall["PCC"],
            "learning_rate": current_lr,
            "epoch_seconds": epoch_seconds,
        }
        history_rows.append(row)
        history_frame = pd.DataFrame(history_rows)
        history_frame.to_csv(out_dir / "training_history.csv", index=False)

        improved = val_overall["MAE"] < best_mae - cfg.min_delta
        if improved:
            best_mae = float(val_overall["MAE"])
            best_epoch = epoch
            epochs_without_improvement = 0
            torch.save(
                {
                    "epoch": epoch,
                    "best_val_mae": best_mae,
                    "model_state_dict": model.state_dict(),
                    "optimizer_state_dict": optimizer.state_dict(),
                    "config": asdict(cfg),
                    "patterns": [asdict(p) for p in patterns],
                    "sequence_length": sequence_length,
                    "parameter_count": parameter_count,
                    "parameter_breakdown": breakdown,
                    "model_name": MODEL_NAME,
                },
                checkpoint_path,
            )
        else:
            epochs_without_improvement += 1

        marker = " *" if improved else ""
        print(
            f"Epoch {epoch:03d} | train={train_result['train_total_loss']:.6f} "
            f"| val MAE={val_overall['MAE']:.6f} "
            f"RMSE={val_overall['RMSE']:.6f} "
            f"SMAPE={val_overall['SMAPE']:.3f}% "
            f"PCC={val_overall['PCC']:.6f} "
            f"| lr={current_lr:.2e} | {epoch_seconds:.1f}s{marker}"
        )

        if epochs_without_improvement >= cfg.patience:
            print(
                f"Early stopping: no validation MAE improvement for {cfg.patience} epochs."
            )
            break

    total_training_seconds = time.time() - start_time
    history_frame = pd.DataFrame(history_rows)
    plot_history(history_frame, out_dir / "training_history.png")

    if not checkpoint_path.exists():
        raise RuntimeError("No best checkpoint was saved")
    checkpoint = torch.load(checkpoint_path, map_location=device)
    model.load_state_dict(checkpoint["model_state_dict"])
    print("\n" + "=" * 80)
    print(f"Best epoch: {best_epoch}")
    print(f"Best validation MAE: {best_mae:.6f}")
    print(f"Training time: {total_training_seconds:.1f} seconds")

    val_overall, val_by_pattern, val_by_type, val_gate, val_examples = evaluate(
        model,
        val_loader,
        device,
        cfg,
        patterns,
        description="Final validation",
        collect_examples=min(cfg.save_prediction_examples, 20),
    )
    save_evaluation(
        out_dir,
        "validation",
        val_overall,
        val_by_pattern,
        val_by_type,
        val_gate,
        val_examples,
    )
    print(
        f"Final validation | MAE={val_overall['MAE']:.6f} "
        f"RMSE={val_overall['RMSE']:.6f} SMAPE={val_overall['SMAPE']:.3f}% "
        f"PCC={val_overall['PCC']:.6f}"
    )
    print("\nValidation by pattern:")
    print(val_by_pattern[["pattern_id", "MAE", "RMSE", "SMAPE", "PCC"]].to_string(index=False))

    # Free validation arrays before loading the test CSV to reduce peak memory.
    del val_loader, val_dataset
    gc.collect()

    test_overall: Optional[Dict[str, float]] = None
    test_inference_seconds: Optional[float] = None
    if not cfg.skip_test:
        print("\nLoading test.csv for one-time final evaluation ...")
        test_dataset = FixedMaskDataset(test_path, pattern_to_index)
        test_loader = make_loader(
            test_dataset,
            cfg.batch_size,
            False,
            cfg.num_workers,
            cfg.seed + 30,
            device,
        )
        if device.type == "cuda":
            torch.cuda.synchronize(device)
        inference_start = time.time()
        test_overall, test_by_pattern, test_by_type, test_gate, test_examples = evaluate(
            model,
            test_loader,
            device,
            cfg,
            patterns,
            description="Final test",
            collect_examples=cfg.save_prediction_examples,
        )
        if device.type == "cuda":
            torch.cuda.synchronize(device)
        test_inference_seconds = time.time() - inference_start
        save_evaluation(
            out_dir,
            "test",
            test_overall,
            test_by_pattern,
            test_by_type,
            test_gate,
            test_examples,
        )
        print(
            f"Final test | MAE={test_overall['MAE']:.6f} "
            f"RMSE={test_overall['RMSE']:.6f} SMAPE={test_overall['SMAPE']:.3f}% "
            f"PCC={test_overall['PCC']:.6f}"
        )
        print("\nTest by pattern:")
        print(test_by_pattern[["pattern_id", "MAE", "RMSE", "SMAPE", "PCC"]].to_string(index=False))

    max_gpu_memory_mb = (torch.cuda.max_memory_allocated(device) / (1024 ** 2) if device.type == "cuda" else 0.0)
    final_summary: Dict[str, object] = {
        "model_name": MODEL_NAME,
        "loss_name": "Smooth L1 (Huber) Loss",
        "script": Path(__file__).name,
        "huber_beta": cfg.huber_beta,
        "lambda_branch": cfg.lambda_branch,
        "local_dim": model.local_dim,
        "periodic_dim": model.periodic_dim,
        "global_dim": model.global_dim,
        "local_blocks": model.local_blocks,
        "periodic_heads": model.periodic_heads,
        "gate_hidden_dim": model.gate_hidden_dim,
        "gate_input": model.gate_input,
        "ablation": model.ablation,
        "best_epoch": best_epoch,
        "best_validation_mae": best_mae,
        "best_validation_mae_during_training": best_mae,
        "parameter_count": parameter_count,
        "parameter_breakdown": breakdown,
        "training_seconds": total_training_seconds,
        "average_epoch_seconds": total_training_seconds / max(len(history_rows), 1),
        "test_inference_seconds": test_inference_seconds,
        "max_gpu_memory_mb": max_gpu_memory_mb,
        "validation": val_overall,
        "test": test_overall,
        "checkpoint": str(checkpoint_path.resolve()),
        "run_config_path": str((out_dir / "run_config.json").resolve()),
    }
    save_json(out_dir / "final_summary.json", final_summary)

