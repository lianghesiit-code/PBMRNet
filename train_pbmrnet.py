"""
CER smart-meter missing-value imputation training script.

Designed for datasets generated by create_cer_online_mask_dataset_fixed.py:

- train.csv: clean 7-day windows. Every clean window is expanded to all nine
  missing patterns in every epoch; exact masks and target days are regenerated
  online for every epoch.
- val.csv / test.csv: fixed masks, with nine configurations:
  random_10/20/40, block_3h/6h/12h, mixed_3h/6h/12h.

Model: simple three-branch gap-aware direct-prediction imputer
1) mask-aware multi-scale within-day convolution branch;
2) same-slot cross-day periodic-attention branch;
3) full-sequence bidirectional GRU branch;
4) a gap-feature-only per-position softmax gate that directly combines the
   three branch predictions. Same-slot observed means are periodic features,
   never a separate output path.

The model never receives pattern_id, missing_type, or missing_level as input.
Those labels are used only for grouped evaluation.
"""

