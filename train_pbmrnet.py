def validate_train_config(cfg: TrainConfig) -> None:
    if cfg.epochs <= 0 or cfg.batch_size <= 0:
        raise ValueError("epochs and batch_size must be positive")
    if cfg.learning_rate <= 0:
        raise ValueError("learning_rate must be positive")
    if min(cfg.local_dim, cfg.periodic_dim, cfg.global_dim) <= 0:
        raise ValueError("branch dimensions must be positive")
    if cfg.global_dim % 2 != 0:
        raise ValueError("global_dim must be even for the bidirectional GRU")
    if cfg.periodic_heads <= 0 or cfg.periodic_dim % cfg.periodic_heads != 0:
        raise ValueError("periodic_dim must be divisible by periodic_heads")
    if cfg.gate_hidden_dim <= 0:
        raise ValueError("gate_hidden_dim must be positive")
    if not (0.0 <= cfg.dropout < 1.0):
        raise ValueError("dropout must be in [0, 1)")
    if cfg.lambda_branch < 0:
        raise ValueError("lambda_branch cannot be negative")
    if cfg.huber_beta <= 0:
        raise ValueError("huber_beta must be positive")


