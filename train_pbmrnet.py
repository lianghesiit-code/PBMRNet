def missing_huber_loss(
    prediction: torch.Tensor,
    target: torch.Tensor,
    mask: torch.Tensor,
    beta: float,
) -> torch.Tensor:
    missing = 1.0 - mask
    point_loss = F.smooth_l1_loss(
        prediction, target, reduction="none", beta=beta
    )
    return (point_loss * missing).sum() / missing.sum().clamp_min(1.0)


def parameter_breakdown(model: nn.Module) -> Dict[str, int]:
    groups = {
        "local_branch": ("local_branch",),
        "periodic_branch": ("periodic_branch",),
        "global_branch": ("global_branch",),
        "gate": ("gate",),
        "prediction_heads": ("local_head", "periodic_head", "global_head"),
    }
    named = dict(model.named_parameters())
    result: Dict[str, int] = {}
    for group, prefixes in groups.items():
        result[group] = sum(
            p.numel() for name, p in named.items()
            if p.requires_grad and any(name == prefix or name.startswith(prefix + ".") for prefix in prefixes)
        )
    result["total"] = sum(p.numel() for p in model.parameters() if p.requires_grad)
    return result


@torch.no_grad()
def run_model_sanity_check(model: SimpleGapAwareThreeBranchImputer, device: torch.device) -> None:
    model.eval()
    batch, length = 2, model.sequence_length
    x = torch.linspace(0.1, 3.0, length, device=device).repeat(batch, 1)
    mask = torch.ones_like(x)
    mask[:, 40:53] = 0.0
    output = model(x * mask, mask)
    expected = (batch, length)
    if output["prediction_norm"].shape != expected:
        raise RuntimeError("Sanity check failed: prediction shape")
    if output["branch_prediction_norm"].shape != (batch, length, 3):
        raise RuntimeError("Sanity check failed: branch prediction shape")
    for key in ("local_residual", "periodic_residual", "global_residual", "periodic_base"):
        if output[key].shape != expected:
            raise RuntimeError(f"Sanity check failed: {key} shape")
    if output["gate_weights"].shape != (batch, length, 3):
        raise RuntimeError("Sanity check failed: gate shape")
    if not torch.allclose(output["gate_weights"].sum(-1), torch.ones_like(x), atol=1e-5):
        raise RuntimeError("Sanity check failed: gates do not sum to one")
    branches = output["branch_prediction_norm"]
    if torch.allclose(branches[..., 0], branches[..., 1]) or torch.allclose(branches[..., 1], branches[..., 2]):
        raise RuntimeError("Sanity check failed: branch predictions are duplicated")
    if output["gap_features"].shape != (batch, length, 4):
        raise RuntimeError("Sanity check failed: gap features")
    dirty = x * mask + (1.0 - mask) * 9999.0
    dirty_output = model(dirty, mask)
    if not torch.allclose(output["periodic_base"], dirty_output["periodic_base"], atol=1e-5):
        raise RuntimeError("Sanity check failed: periodic base uses missing target values")
    for key in ("prediction_norm", "branch_prediction_norm", "gate_weights", "periodic_base"):
        if not torch.isfinite(output[key]).all():
            raise RuntimeError(f"Sanity check failed: non-finite {key}")
    all_missing = torch.zeros_like(mask)
    extreme = model(torch.zeros_like(x), all_missing)
    if not torch.isfinite(extreme["prediction_norm"]).all():
        raise RuntimeError("Sanity check failed: all-missing input is unsafe")
    pred = torch.tensor([[0.0, 3.0]], device=device)
    target = torch.zeros_like(pred)
    missing_mask = torch.zeros_like(pred)
    if torch.allclose(
        missing_huber_loss(pred, target, missing_mask, 0.2),
        missing_huber_loss(pred, target, missing_mask, 1.0),
    ):
        raise RuntimeError("Sanity check failed: Huber beta has no effect")
    count = sum(p.numel() for p in model.parameters() if p.requires_grad)
    if count > 500_000:
        raise RuntimeError(f"Parameter limit exceeded: {count} > 500000")
    model.train()


def compute_training_loss(
    output: Mapping[str, torch.Tensor],
    y: torch.Tensor,
    mask: torch.Tensor,
    beta: float,
    lambda_branch: float,
) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    y_norm = (y - output["mean"]) / output["std"]
    main_loss = missing_huber_loss(
        output["prediction_norm"], y_norm, mask, beta
    )
    if lambda_branch > 0:
        branch_losses = [
            missing_huber_loss(
                output["branch_prediction_norm"][..., i], y_norm, mask, beta
            )
            for i in range(3)
        ]
        branch_loss = torch.stack(branch_losses).mean()
    else:
        branch_loss = main_loss.detach() * 0.0
    total = main_loss + lambda_branch * branch_loss
    return total, main_loss, branch_loss


class MetricAccumulator:
    def __init__(self, patterns: Sequence[PatternSpec]) -> None:
        self.patterns = tuple(patterns)
        self.overall = self._empty_stats()
        self.by_pattern = {p.pattern_id: self._empty_stats() for p in patterns}
        type_names = sorted({p.missing_type for p in patterns})
        self.by_type = {name: self._empty_stats() for name in type_names}
        self.gate_by_pattern = {
            p.pattern_id: {"sum": np.zeros(3, dtype=np.float64), "count": 0}
            for p in patterns
        }
        self.loss_sum = 0.0
        self.loss_weight = 0

    @staticmethod
    def _empty_stats() -> Dict[str, float]:
        return {
            "abs": 0.0, "sq": 0.0, "smape": 0.0, "count": 0.0,
            "pcc_sum": 0.0, "pcc_count": 0.0,
        }

    @staticmethod
    def _safe_pcc(pred: torch.Tensor, true: torch.Tensor, eps: float = 1e-8):
        """Sample-wise PCC on missing positions; undefined samples are excluded."""
        if pred.numel() < 2:
            return None
        pred_centered = pred - pred.mean()
        true_centered = true - true.mean()
        pred_energy = torch.sum(pred_centered ** 2)
        true_energy = torch.sum(true_centered ** 2)
        denom = torch.sqrt(pred_energy * true_energy)
        if not torch.isfinite(denom) or float(denom.item()) <= eps:
            return None
        value = torch.sum(pred_centered * true_centered) / denom
        if not torch.isfinite(value):
            return None
        return float(value.clamp(-1.0, 1.0).item())

    @classmethod
    def _add_pcc(cls, stats: Dict[str, float], pred: torch.Tensor, true: torch.Tensor) -> None:
        value = cls._safe_pcc(pred, true)
        if value is not None:
            stats["pcc_sum"] += value
            stats["pcc_count"] += 1.0

    @staticmethod
    def _add(stats: Dict[str, float], pred: torch.Tensor, true: torch.Tensor) -> None:
        if pred.numel() == 0:
            return
        error = pred - true
        stats["abs"] += float(error.abs().sum().item())
        stats["sq"] += float((error**2).sum().item())
        smape = 200.0 * error.abs() / (pred.abs() + true.abs() + 1e-6)
        stats["smape"] += float(smape.sum().item())
        stats["count"] += float(pred.numel())

    def update(
        self,
        pred: torch.Tensor,
        true: torch.Tensor,
        mask: torch.Tensor,
        pattern_indices: torch.Tensor,
        gate_weights: torch.Tensor,
        loss: float,
    ) -> None:
        missing = mask < 0.5
        self._add(self.overall, pred[missing], true[missing])
        self.loss_sum += float(loss) * pred.shape[0]
        self.loss_weight += int(pred.shape[0])

        # PCC is intentionally sample-wise and macro-averaged. It is not
        # weighted by the number of missing points in a sample.
        for sample_index in range(pred.shape[0]):
            sample_missing = missing[sample_index]
            sample_pred = pred[sample_index][sample_missing]
            sample_true = true[sample_index][sample_missing]
            pattern = self.patterns[int(pattern_indices[sample_index].item())]
            self._add_pcc(self.overall, sample_pred, sample_true)
            self._add_pcc(self.by_pattern[pattern.pattern_id], sample_pred, sample_true)
            self._add_pcc(self.by_type[pattern.missing_type], sample_pred, sample_true)

        for pattern_index, pattern in enumerate(self.patterns):
            sample_selection = pattern_indices == pattern_index
            if not torch.any(sample_selection):
                continue
            local_missing = missing[sample_selection]
            local_pred = pred[sample_selection][local_missing]
            local_true = true[sample_selection][local_missing]
            self._add(self.by_pattern[pattern.pattern_id], local_pred, local_true)
            self._add(self.by_type[pattern.missing_type], local_pred, local_true)

            selected_gate = gate_weights[sample_selection][local_missing]
            if selected_gate.numel() > 0:
                self.gate_by_pattern[pattern.pattern_id]["sum"] += (
                    selected_gate.sum(dim=0).detach().cpu().numpy()
                )
                self.gate_by_pattern[pattern.pattern_id]["count"] += int(
                    selected_gate.shape[0]
                )

    @staticmethod
    def _finalize(stats: Mapping[str, float]) -> Dict[str, float]:
        count = max(float(stats["count"]), 1.0)
        pcc_count = int(stats["pcc_count"])
        return {
            "MAE": float(stats["abs"] / count),
            "RMSE": float(math.sqrt(stats["sq"] / count)),
            "SMAPE": float(stats["smape"] / count),
            "PCC": float(stats["pcc_sum"] / pcc_count) if pcc_count else float("nan"),
            "missing_points": int(stats["count"]),
            "valid_pcc_samples": pcc_count,
        }

    def finalize(self) -> Tuple[Dict[str, float], pd.DataFrame, pd.DataFrame, pd.DataFrame]:
        overall = self._finalize(self.overall)
        overall["loss"] = self.loss_sum / max(self.loss_weight, 1)

        pattern_rows = []
        for pattern in self.patterns:
            row = {
                "pattern_id": pattern.pattern_id,
                "missing_type": pattern.missing_type,
                "missing_level": pattern.missing_level,
            }
            row.update(self._finalize(self.by_pattern[pattern.pattern_id]))
            pattern_rows.append(row)

        type_rows = []
        for type_name, stats in self.by_type.items():
            row = {"missing_type": type_name}
            row.update(self._finalize(stats))
            type_rows.append(row)

        gate_rows = []
        for pattern in self.patterns:
            gate_stats = self.gate_by_pattern[pattern.pattern_id]
            count = max(int(gate_stats["count"]), 1)
            means = gate_stats["sum"] / count
            gate_rows.append(
                {
                    "pattern_id": pattern.pattern_id,
                    "local_weight": float(means[0]),
                    "period_weight": float(means[1]),
                    "global_weight": float(means[2]),
                    "missing_points": int(gate_stats["count"]),
                }
            )

        return (
            overall,
            pd.DataFrame(pattern_rows),
            pd.DataFrame(type_rows),
            pd.DataFrame(gate_rows),
        )


