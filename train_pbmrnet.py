class ChannelLayerNorm(nn.Module):
    """LayerNorm for tensors shaped [B, C, T]."""

    def __init__(self, channels: int) -> None:
        super().__init__()
        self.norm = nn.LayerNorm(channels)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.norm(x.transpose(1, 2)).transpose(1, 2)


class TemporalResidualBlock(nn.Module):
    def __init__(self, d_model: int, dropout: float) -> None:
        super().__init__()
        self.depthwise = nn.Conv1d(d_model, d_model, kernel_size=3, padding=1, groups=d_model)
        self.pointwise1 = nn.Conv1d(d_model, 2 * d_model, kernel_size=1)
        self.pointwise2 = nn.Conv1d(2 * d_model, d_model, kernel_size=1)
        self.norm = ChannelLayerNorm(d_model)
        self.dropout = nn.Dropout(dropout)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        residual = x
        x = self.depthwise(x)
        x = F.gelu(self.pointwise1(x))
        x = self.dropout(self.pointwise2(x))
        return self.norm(residual + x)


class MaskAwareLocalBranch(nn.Module):
    """Within-day multi-scale mask-normalized temporal convolution."""

    def __init__(self, d_model: int, dropout: float, blocks: int = 2) -> None:
        super().__init__()
        self.kernels = (3, 5, 7)
        self.scale_convs = nn.ModuleList(
            [nn.Conv1d(1, 1, kernel_size=k, padding=k // 2, bias=False) for k in self.kernels]
        )
        self.input_proj = nn.Conv1d(7, d_model, kernel_size=1)
        self.blocks = nn.ModuleList([TemporalResidualBlock(d_model, dropout) for _ in range(blocks)])

    def forward(
        self,
        x_norm: torch.Tensor,
        mask: torch.Tensor,
        slot_sin: torch.Tensor,
        slot_cos: torch.Tensor,
        window_days: int,
    ) -> torch.Tensor:
        batch, length = x_norm.shape
        x_day = x_norm.view(batch * window_days, 1, SLOTS_PER_DAY)
        m_day = mask.view(batch * window_days, 1, SLOTS_PER_DAY)
        sin_day = slot_sin.view(1, 1, SLOTS_PER_DAY).expand(batch * window_days, -1, -1)
        cos_day = slot_cos.view(1, 1, SLOTS_PER_DAY).expand(batch * window_days, -1, -1)

        scales: List[torch.Tensor] = []
        for conv, kernel_size in zip(self.scale_convs, self.kernels):
            numerator = conv(x_day * m_day)
            kernel = torch.ones(
                1, 1, kernel_size, device=x_day.device, dtype=x_day.dtype
            )
            valid_count = F.conv1d(m_day, kernel, padding=kernel_size // 2)
            normalized = numerator * (float(kernel_size) / valid_count.clamp_min(1.0))
            normalized = torch.where(valid_count > 0, normalized, torch.zeros_like(normalized))
            scales.append(normalized)

        features = torch.cat([x_day, m_day, sin_day, cos_day] + scales, dim=1)
        hidden = F.gelu(self.input_proj(features))
        for block in self.blocks:
            hidden = block(hidden)
        hidden = hidden.transpose(1, 2).reshape(batch, length, -1)
        return hidden


class PeriodicAttentionBranch(nn.Module):
    """Attention only across days for the same half-hour slot."""

    def __init__(self, d_model: int, num_heads: int, dropout: float) -> None:
        super().__init__()
        self.input_proj = nn.Linear(6, d_model)
        self.attn = nn.MultiheadAttention(
            embed_dim=d_model,
            num_heads=num_heads,
            dropout=dropout,
            batch_first=True,
        )
        self.norm1 = nn.LayerNorm(d_model)
        self.ffn = nn.Sequential(
            nn.Linear(d_model, 2 * d_model),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(2 * d_model, d_model),
            nn.Dropout(dropout),
        )
        self.norm2 = nn.LayerNorm(d_model)

    def forward(
        self,
        x_norm: torch.Tensor,
        mask: torch.Tensor,
        time_features: torch.Tensor,
        window_days: int,
    ) -> torch.Tensor:
        batch = x_norm.shape[0]
        x_grid = x_norm.view(batch, window_days, SLOTS_PER_DAY)
        m_grid = mask.view(batch, window_days, SLOTS_PER_DAY)
        t_grid = time_features.view(batch, window_days, SLOTS_PER_DAY, 4)
        features = torch.cat([x_grid.unsqueeze(-1), m_grid.unsqueeze(-1), t_grid], dim=-1)

        # [B, D, S, F] -> [B*S, D, F]
        tokens = features.permute(0, 2, 1, 3).reshape(batch * SLOTS_PER_DAY, window_days, 6)
        tokens = self.input_proj(tokens)
        key_padding_mask = (
            m_grid.permute(0, 2, 1).reshape(batch * SLOTS_PER_DAY, window_days) < 0.5
        )

        # Defensive handling for unseen masks where all seven same-slot values are missing.
        all_missing = key_padding_mask.all(dim=1)
        if torch.any(all_missing):
            key_padding_mask = key_padding_mask.clone()
            tokens = tokens.clone()
            key_padding_mask[all_missing, 0] = False
            tokens[all_missing, 0] = 0.0

        attended, _ = self.attn(
            tokens,
            tokens,
            tokens,
            key_padding_mask=key_padding_mask,
            need_weights=False,
        )
        hidden = self.norm1(tokens + attended)
        hidden = self.norm2(hidden + self.ffn(hidden))
        hidden = hidden.view(batch, SLOTS_PER_DAY, window_days, -1)
        hidden = hidden.permute(0, 2, 1, 3).reshape(batch, window_days * SLOTS_PER_DAY, -1)
        return hidden


class GlobalBiGRUBranch(nn.Module):
    def __init__(self, d_model: int, dropout: float) -> None:
        super().__init__()
        self.input_proj = nn.Linear(6, d_model)
        self.gru = nn.GRU(
            input_size=d_model,
            hidden_size=d_model // 2,
            num_layers=1,
            batch_first=True,
            bidirectional=True,
        )
        self.norm = nn.LayerNorm(d_model)
        self.dropout = nn.Dropout(dropout)

    def forward(
        self,
        x_norm: torch.Tensor,
        mask: torch.Tensor,
        time_features: torch.Tensor,
    ) -> torch.Tensor:
        features = torch.cat([x_norm.unsqueeze(-1), mask.unsqueeze(-1), time_features], dim=-1)
        embedded = F.gelu(self.input_proj(features))
        hidden, _ = self.gru(embedded)
        return self.norm(embedded + self.dropout(hidden))


def compute_gap_features(mask: torch.Tensor, window_days: int) -> torch.Tensor:
    """Returns [missing, normalized gap length, local ratio, periodic ratio]."""
    batch = mask.shape[0]
    m = mask.view(batch * window_days, SLOTS_PER_DAY)
    missing = 1.0 - m

    forward = torch.zeros_like(m)
    run = torch.zeros(batch * window_days, device=m.device, dtype=m.dtype)
    for slot in range(SLOTS_PER_DAY):
        run = (run + 1.0) * missing[:, slot]
        forward[:, slot] = run

    backward = torch.zeros_like(m)
    run.zero_()
    for slot in range(SLOTS_PER_DAY - 1, -1, -1):
        run = (run + 1.0) * missing[:, slot]
        backward[:, slot] = run

    gap_length = (forward + backward - 1.0).clamp_min(0.0) * missing
    gap_length = gap_length / float(SLOTS_PER_DAY)
    local_ratio = F.avg_pool1d(
        m.unsqueeze(1), kernel_size=7, stride=1, padding=3
    ).squeeze(1)

    m_grid = mask.view(batch, window_days, SLOTS_PER_DAY)
    periodic_ratio = m_grid.mean(dim=1, keepdim=True).expand(-1, window_days, -1)

    output = torch.stack(
        [
            missing,
            gap_length,
            local_ratio,
            periodic_ratio.reshape(batch * window_days, SLOTS_PER_DAY),
        ],
        dim=-1,
    )
    return output.reshape(batch, window_days * SLOTS_PER_DAY, 4)



class SimpleGapAwareThreeBranchImputer(nn.Module):
    """Observed periodic base plus three residuals fused by a gap-aware gate."""
    def __init__(self, sequence_length: int, local_dim: int = 80,
                 periodic_dim: int = 80, global_dim: int = 160,
                 local_blocks: int = 2, periodic_heads: int = 4,
                 gate_hidden_dim: int = 16, gate_input: str = "gap_only",
                 dropout: float = 0.1, ablation: str = "none") -> None:
        super().__init__()
        if sequence_length % SLOTS_PER_DAY != 0:
            raise ValueError("sequence_length must be divisible by SLOTS_PER_DAY")
        self.sequence_length = int(sequence_length)
        self.window_days = sequence_length // SLOTS_PER_DAY
        self.local_dim = local_dim
        self.periodic_dim = periodic_dim
        self.global_dim = global_dim
        self.local_blocks = local_blocks
        self.periodic_heads = periodic_heads
        self.gate_hidden_dim = gate_hidden_dim
        self.gate_input = gate_input
        self.ablation = ablation
        self.periodic_heads = periodic_heads

        self.local_branch = MaskAwareLocalBranch(self.local_dim, dropout, local_blocks)
        self.periodic_branch = PeriodicAttentionBranch(self.periodic_dim, periodic_heads, dropout)
        self.global_branch = GlobalBiGRUBranch(self.global_dim, dropout)
        self.local_head = nn.Linear(self.local_dim, 1)
        self.periodic_head = nn.Linear(self.periodic_dim, 1)
        self.global_head = nn.Linear(self.global_dim, 1)
        gate_input_dim = 4 if gate_input == "gap_only" else 8
        self.gate = nn.Sequential(
            nn.Linear(gate_input_dim, gate_hidden_dim), nn.GELU(), nn.Dropout(dropout),
            nn.Linear(gate_hidden_dim, 3)
        )
        nn.init.zeros_(self.gate[-1].bias)

        day_index = torch.arange(self.window_days, dtype=torch.float32).repeat_interleave(SLOTS_PER_DAY)
        slot_index = torch.arange(SLOTS_PER_DAY, dtype=torch.float32).repeat(self.window_days)
        time_features = torch.stack([
            torch.sin(2 * math.pi * slot_index / SLOTS_PER_DAY),
            torch.cos(2 * math.pi * slot_index / SLOTS_PER_DAY),
            torch.sin(2 * math.pi * day_index / max(self.window_days, 1)),
            torch.cos(2 * math.pi * day_index / max(self.window_days, 1)),
        ], dim=-1)
        self.register_buffer("time_features", time_features, persistent=False)
        trainable = sum(p.numel() for p in self.parameters() if p.requires_grad)
        if trainable > 500_000:
            raise RuntimeError(f"Parameter limit exceeded: {trainable} > 500000")
        disabled = {
            "no_local": (self.local_branch, self.local_head),
            "no_periodic": (self.periodic_branch, self.periodic_head),
            "no_global": (self.global_branch, self.global_head),
        }.get(ablation, ())
        for module in disabled:
            for parameter in module.parameters():
                parameter.requires_grad_(False)


    @staticmethod
    def observed_normalize(x: torch.Tensor, mask: torch.Tensor):
        count = mask.sum(dim=1, keepdim=True).clamp_min(1.0)
        mean = (x * mask).sum(dim=1, keepdim=True) / count
        variance = (((x - mean) ** 2) * mask).sum(dim=1, keepdim=True) / count
        std = variance.sqrt().clamp_min(1e-3)
        return ((x - mean) / std) * mask, mean, std

    def periodic_base(self, x_norm: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
        batch = x_norm.shape[0]
        x_grid = x_norm.view(batch, self.window_days, SLOTS_PER_DAY)
        m_grid = mask.view(batch, self.window_days, SLOTS_PER_DAY)
        slot_count = m_grid.sum(dim=1, keepdim=True)
        slot_mean = (x_grid * m_grid).sum(dim=1, keepdim=True) / slot_count.clamp_min(1.0)
        day_count = m_grid.sum(dim=2, keepdim=True)
        day_mean = (x_grid * m_grid).sum(dim=2, keepdim=True) / day_count.clamp_min(1.0)
        sample_count = mask.sum(dim=1, keepdim=True)
        sample_mean = (x_norm * mask).sum(dim=1, keepdim=True) / sample_count.clamp_min(1.0)
        fallback = torch.where(
            day_count > 0,
            day_mean.expand_as(x_grid),
            torch.where(
                sample_count.view(batch, 1, 1) > 0,
                sample_mean.view(batch, 1, 1).expand_as(x_grid),
                torch.zeros_like(x_grid),
            ),
        )
        base = torch.where(
            slot_count.expand_as(x_grid) > 0,
            slot_mean.expand_as(x_grid),
            fallback,
        )
        return base.reshape(batch, -1)

    def forward(self, x: torch.Tensor, mask: torch.Tensor) -> Dict[str, torch.Tensor]:
        x_norm, mean, std = self.observed_normalize(x, mask)
        tf = self.time_features.unsqueeze(0).expand(x.shape[0], -1, -1)
        local = self.local_branch(
            x_norm, mask,
            self.time_features[:SLOTS_PER_DAY, 0],
            self.time_features[:SLOTS_PER_DAY, 1],
            self.window_days,
        )
        periodic = self.periodic_branch(x_norm, mask, tf, self.window_days)
        global_feature = self.global_branch(x_norm, mask, tf)
        gap = compute_gap_features(mask, self.window_days)
        local_residual = self.local_head(local).squeeze(-1)
        periodic_residual = self.periodic_head(periodic).squeeze(-1)
        global_residual = self.global_head(global_feature).squeeze(-1)
        branch_residual = torch.stack([local_residual, periodic_residual, global_residual], dim=-1)
        gate_features = gap if self.gate_input == "gap_only" else torch.cat([gap, tf], dim=-1)
        if self.ablation == "no_gap":
            gate_features = torch.zeros_like(gate_features)
        valid = torch.ones(3, device=x.device, dtype=x.dtype)
        if self.ablation == "no_local": valid[0] = 0.0
        if self.ablation == "no_periodic": valid[1] = 0.0
        if self.ablation == "no_global": valid[2] = 0.0
        if self.ablation == "average_gate":
            gate_weights = valid.view(1, 1, 3).expand(x.shape[0], x.shape[1], -1)
        else:
            gate_weights = torch.softmax(self.gate(gate_features), dim=-1) * valid.view(1, 1, 3)
        gate_weights = gate_weights / gate_weights.sum(dim=-1, keepdim=True).clamp_min(1e-8)
        periodic_base = self.periodic_base(x_norm, mask)
        if self.ablation == "no_periodic_base":
            periodic_base = torch.zeros_like(periodic_base)
        branch_prediction_norm = periodic_base.unsqueeze(-1) + branch_residual
        gated_residual = (gate_weights * branch_residual).sum(dim=-1)
        prediction_norm = periodic_base + gated_residual
        return {"prediction_norm": prediction_norm, "branch_prediction_norm": branch_prediction_norm,
                "gate_weights": gate_weights, "mean": mean, "std": std,
                "gap_features": gap,
                "periodic_base": periodic_base,
                "local_residual": local_residual,
                "periodic_residual": periodic_residual,
                "global_residual": global_residual}


